import fs from 'fs';
import path from 'path';

const skillsCache = new Map<string, string>();

export function loadSkills(exclude: string[] = []): string {
  const cacheKey = exclude.sort().join(',') || '__all__';
  if (skillsCache.has(cacheKey)) return skillsCache.get(cacheKey)!;

  const skillsDir = path.join(process.cwd(), 'skills');
  const files = [
    'advertising-law.md',
    'administrative-law.md',
    'document-formats.md',
    'case-strategies.md',
    'workflow-analysis.md',
  ].filter(f => !exclude.includes(f));

  const result = files
    .filter(f => fs.existsSync(path.join(skillsDir, f)))
    .map(f => {
      const content = fs.readFileSync(path.join(skillsDir, f), 'utf-8');
      return `## ${f.replace('.md', '')}\n\n${content}`;
    })
    .join('\n\n---\n\n');

  skillsCache.set(cacheKey, result);
  return result;
}

